BY_KEY = {t.key: t for t in TERMS}


def tip(key: str) -> str:
    """Tooltip text (plain) for Streamlit ``help=`` arguments."""
    t = BY_KEY[key]
    return t.basic + (f"\n\n{t.more}" if t.more else "")
